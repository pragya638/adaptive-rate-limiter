package com.example.ratelimiter.adaptive;

public class TrafficAssessment {
    private final Double currentRequestRate;
    private final Double ewmaRequestRate;
    private final Double errorRate;
    private final Long totalRequests;
    private final Long allowedRequests;
    private final Long rejectedRequests;
    private final Long windowRequestCount;
    private final Double clientErrorRate;
    private final Long windowSequence;
    private final Double windowDurationSeconds;

    public TrafficAssessment(Double currentRequestRate, Double ewmaRequestRate, Double errorRate,
            Long totalRequests, Long allowedRequests, Long rejectedRequests) {
        this(currentRequestRate, ewmaRequestRate, errorRate, totalRequests, allowedRequests, rejectedRequests,
                null, null);
    }

    public TrafficAssessment(Double currentRequestRate, Double ewmaRequestRate, Double errorRate,
            Long totalRequests, Long allowedRequests, Long rejectedRequests,
            Long windowRequestCount, Double clientErrorRate) {
        this(currentRequestRate, ewmaRequestRate, errorRate, totalRequests, allowedRequests, rejectedRequests,
                windowRequestCount, clientErrorRate, null, null);
    }

    public TrafficAssessment(Double currentRequestRate, Double ewmaRequestRate, Double errorRate,
            Long totalRequests, Long allowedRequests, Long rejectedRequests,
            Long windowRequestCount, Double clientErrorRate,
            Long windowSequence, Double windowDurationSeconds) {
        this.currentRequestRate = currentRequestRate;
        this.ewmaRequestRate = ewmaRequestRate;
        this.errorRate = errorRate;
        this.totalRequests = totalRequests;
        this.allowedRequests = allowedRequests;
        this.rejectedRequests = rejectedRequests;
        this.windowRequestCount = windowRequestCount;
        this.clientErrorRate = clientErrorRate;
        this.windowSequence = windowSequence;
        this.windowDurationSeconds = windowDurationSeconds;
    }

    public static TrafficAssessment empty() {
        return new TrafficAssessment(null, null, null, null, null, null);
    }

    public Double getCurrentRequestRate() {
        return currentRequestRate;
    }

    public Double getEwmaRequestRate() {
        return ewmaRequestRate;
    }

    public Double getErrorRate() {
        return errorRate;
    }

    public Long getTotalRequests() {
        return totalRequests;
    }

    public Long getAllowedRequests() {
        return allowedRequests;
    }

    public Long getRejectedRequests() {
        return rejectedRequests;
    }

    public Long getWindowRequestCount() {
        return windowRequestCount;
    }

    public Double getClientErrorRate() {
        return clientErrorRate;
    }

    public Long getWindowSequence() {
        return windowSequence;
    }

    public Double getWindowDurationSeconds() {
        return windowDurationSeconds;
    }

    /**
     * Error rate used for adaptive control: client/server errors only, excluding
     * rate-limit rejections generated by the limiter itself.
     */
    public Double getEffectiveErrorRate() {
        return clientErrorRate != null ? clientErrorRate : errorRate;
    }

    /**
     * Request count used for ML features. Prefers the completed observation
     * window over the lifetime total so feature semantics remain stable.
     */
    public Long getEffectiveRequestCount() {
        return windowRequestCount != null ? windowRequestCount : totalRequests;
    }
}
